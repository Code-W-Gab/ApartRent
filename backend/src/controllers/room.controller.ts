import { RequestHandler } from "express";
import { unlink } from "node:fs/promises";
import path from "node:path";
import { roomUploadDirectory } from "../middleware/roomUpload";
import { createRoomDTO, IdParams, IRoom, updateRoomDto } from "../types/room.types";
import roomSchema from "../models/room.schema";

export const createRoom: RequestHandler = async (req, res) => {
  const files = (req.files as Express.Multer.File[] | undefined) ?? [];

  try {
    // FormData sends the room details as a JSON string.
    const input = JSON.parse(req.body.data);

    if (!input || typeof input !== "object" || Array.isArray(input)) {
      throw new Error("Invalid room data");
    }

    const newRoom = await roomSchema.create({
      roomNumber: input.roomNumber,
      floor: input.floor,
      type: input.type,
      monthlyRent: input.monthlyRent,
      deposit: input.deposit,
      status: input.status,
      description: input.description,
      amenities: input.amenities,
      notes: input.notes,

      // Save URL paths in MongoDB.
      photos: files.map((file) => `/uploads/rooms/${file.filename}`),
    });

    res.status(201).json({
      success: true,
      message: "Room added successfully",
      data: newRoom,
    });
  } catch (error) {
    // Remove uploaded files if saving the room fails.
    await Promise.allSettled(
      files.map((file) => unlink(file.path))
    );

    const invalidInput =
      error instanceof SyntaxError ||
      (error instanceof Error &&
        ["ValidationError", "CastError"].includes(error.name)) ||
      (error instanceof Error && error.message === "Invalid room data");

    res.status(invalidInput ? 400 : 500).json({
      success: false,
      message: invalidInput
        ? "Please check the room details."
        : "Could not create the room.",
    });
  }
};

class RoomUpdateError extends Error {
  status: number;

  constructor(message: string, status = 400) {
    super(message);
    this.status = status;
  }
}

export const updateRoom: RequestHandler<IdParams> = async (req, res) => {
  const files = (req.files as Express.Multer.File[] | undefined) ?? [];
  let saved = false;

  try {
    const input = JSON.parse(req.body.data);

    if (!input || typeof input !== "object" || Array.isArray(input)) {
      throw new RoomUpdateError("Invalid room data.");
    }

    const room = await roomSchema.findById(req.params.id);

    if (!room) {
      throw new RoomUpdateError("Room not found.", 404);
    }

    const oldPhotos = [...(room.photos ?? [])];

    // Missing existingPhotos means keep all current photos.
    // An empty array means remove all current photos.
    const requestedPhotos = input.existingPhotos ?? oldPhotos;

    if (
      !Array.isArray(requestedPhotos) ||
      !requestedPhotos.every(
        (photo: unknown) =>
          typeof photo === "string" && oldPhotos.includes(photo)
      )
    ) {
      throw new RoomUpdateError("Invalid existing photos.");
    }

    const keptPhotos = [...new Set(requestedPhotos as string[])];

    if (keptPhotos.length + files.length > 6) {
      throw new RoomUpdateError("A room can have a maximum of 6 photos.");
    }

    // Only allow editable room fields.
    const editableFields = [
      "roomNumber",
      "floor",
      "type",
      "monthlyRent",
      "deposit",
      "status",
      "description",
      "amenities",
      "notes",
    ] as const;

    for (const field of editableFields) {
      if (Object.prototype.hasOwnProperty.call(input, field)) {
        room.set(field, input[field]);
      }
    }

    room.photos = [
      ...keptPhotos,
      ...files.map((file) => `/uploads/rooms/${file.filename}`),
    ];

    await room.save();
    saved = true;

    // Delete removed files only after the database update succeeds.
    const removedPhotos = oldPhotos.filter(
      (photo) => !keptPhotos.includes(photo)
    );

    const cleanupResults = await Promise.allSettled(
      removedPhotos.map(async (photo) => {
        const prefix = "/uploads/rooms/";

        if (!photo.startsWith(prefix)) return;

        const filename = photo.slice(prefix.length);

        // Accept only filenames generated by your upload middleware.
        // This prevents paths outside the uploads directory.
        if (!/^[a-f0-9-]+\.(jpg|png|webp)$/i.test(filename)) return;

        await unlink(path.join(roomUploadDirectory, filename));
      })
    );

    cleanupResults.forEach((result) => {
      if (result.status === "rejected") {
        console.error("Could not delete an old room photo:", result.reason);
      }
    });

    res.status(200).json({
      success: true,
      message: "Room updated successfully",
      data: room,
    });
  } catch (error) {
    // Remove new uploads if the database update failed.
    if (!saved) {
      await Promise.allSettled(
        files.map((file) => unlink(file.path))
      );
    }

    const invalidInput =
      error instanceof SyntaxError ||
      (error instanceof Error &&
        ["ValidationError", "CastError"].includes(error.name));

    const status =
      error instanceof RoomUpdateError
        ? error.status
        : invalidInput
          ? 400
          : 500;

    res.status(status).json({
      success: false,
      message:
        error instanceof RoomUpdateError
          ? error.message
          : invalidInput
            ? "Please check the room details."
            : "Could not update the room.",
    });
  }
};

export const deleteRoom: RequestHandler<IdParams, {}, {}> = async (req, res) => {
  try {
    const room = await roomSchema.findByIdAndDelete(req.params.id);

    if(!room) return res.status(404).json({ message: "Room not found" })

    res.status(200).json({
      success: true,
      message: "Room deleted successfully"
    })
  } catch (error) {
    res.status(500).json({
      success: false,
      message: "Internal server error"
    })
  }
}

export const getRoom: RequestHandler = async (req, res) => {
  try {
    // search filter by room number
    const roomNumberQuery = req.query.roomNumber;

    const filter: {
      $expr?: {
        $regexMatch: {
          input: { $toString: string };
          regex: string;
        };
      };
      status?: IRoom["status"];
      floor?: IRoom["floor"];
    } = {};

    if (roomNumberQuery !== undefined) {
      if (
        typeof roomNumberQuery !== "string" ||
        !/^\d+$/.test(roomNumberQuery.trim())
      ) {
        return res.status(400).json({
          success: false,
          message: "roomNumber must contain digits only",
        });
      }

      filter.$expr = {
        $regexMatch: {
          input: { $toString: "$roomNumber" },
          regex: roomNumberQuery.trim(),
        },
      };
    }

    const statusQuery = req.query.status;
    if (statusQuery !== undefined) {
      const validStatuses: IRoom["status"][] = [
        "Available",
        "Occupied",
        "Reserved",
      ];

      const matchedStatus =
        typeof statusQuery === "string"
          ? validStatuses.find((status) => status === statusQuery)
          : undefined;

      if (!matchedStatus) {
        return res.status(400).json({
          success: false,
          message: "Invalid status",
        });
      }

      filter.status = matchedStatus;
    }

    const floorQuery = req.query.floor;
    if (floorQuery !== undefined) {
      const floorNumber =
        typeof floorQuery === "string" ? Number(floorQuery) : NaN;
      const validFloor = ([1, 2, 3, 4] as const).find(
        (floor) => floor === floorNumber,
      );

      if (!validFloor) {
        return res.status(400).json({
          success: false,
          message: "Invalid floor",
        });
      }

      filter.floor = validFloor;
    }

    // get all rooms
    const room = await roomSchema.find(filter);

    res.status(200).json({
      success: true,
      message: "Room retrieved successfully",
      data: room
    })
  } catch (error) {
    res.status(500).json({
      success: false,
      message: "Internal server error"
    })
  }
}